-- Настройки приложения, редактируемые администратором. Первый потребитель —
-- правила геймификации (ключ 'gamification'): XP за тему, пороги уровней,
-- порог зачёта теста и условия значков.
--
-- Одна таблица «ключ → JSON», а не колонки под каждую настройку: набор полей
-- у правил меняется вместе с продуктом, и заводить миграцию на каждую галочку
-- дороже, чем валидировать JSON в коде (backend/src/settings.js).
--
-- Строки специально не заполняются значениями по умолчанию: пока ключа нет,
-- backend отдаёт дефолты из gamification.js. Так значения по умолчанию описаны
-- ровно в одном месте и не расходятся с миграцией, а запись появляется только
-- когда администратор что-то изменил.

CREATE TABLE IF NOT EXISTS app_settings (
  key        TEXT        PRIMARY KEY,
  value      JSONB       NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by BIGINT      NULL REFERENCES users (id)
);
